// The Navigator's AI text (#116) with the shared contract sample. Excluded from `tsc` like the
// other *.contract.test files: the Docker build copies only web/.
import {screen, within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {afterEach, beforeEach, describe, expect, it, vi} from 'vitest';
import sample from '../../../contract/fixtures/snapshot.sample.json';
import {parseSnapshot} from '../contract/snapshot';
import {toLoadedSnapshot} from '../data/snapshotClient';
import {renderApp} from '../test/renderApp';

const loaded = (changes: Record<string, unknown> = {}) =>
  toLoadedSnapshot(parseSnapshot({...sample, ...changes}));

const aiSource = (status: string, message: string | null = null) => ({
  id: 'navigator-ai',
  name: 'AI summary',
  status,
  fetchedAt: '2026-11-02T06:00:30Z',
  message,
});

const panel = () => screen.getByRole('complementary', {name: 'Navigator'});
const menu = () => screen.getByRole('navigation', {name: 'Main menu'});

describe('Navigator AI text', () => {
  beforeEach(() => {
    vi.useFakeTimers({toFake: ['Date']});
    vi.setSystemTime(new Date('2026-11-02T06:05:00Z'));
  });
  afterEach(() => vi.useRealTimers());

  it("shows the page's summary, deviations and suggestions as lists", () => {
    renderApp({path: '/rainmaker/overview', loaded: loaded()});

    expect(panel()).toHaveTextContent(
      'The sprint is on track, but one red risk and one overdue question need the owners.'
    );
    const deviations = within(panel()).getByRole('list', {name: 'Deviations'});
    expect(
      within(deviations)
        .getAllByRole('listitem')
        .map(item => item.textContent)
    ).toEqual([
      'Q-7 about the consent text is overdue since 30 Oct.',
      'Risk R-3 (pilot publisher not signed) is red.',
    ]);
    const suggestions = within(panel()).getByRole('list', {
      name: 'Suggestions',
    });
    expect(within(suggestions).getAllByRole('listitem')).toHaveLength(1);
  });

  it('always labels the text as AI, with model and time, and links to its data', () => {
    renderApp({path: '/rainmaker/overview', loaded: loaded()});

    expect(panel()).toHaveTextContent(
      'Generated by AI (gpt-6-luna) at 07:00. May contain mistakes.'
    );
    expect(
      within(panel()).getByRole('link', {
        name: 'Based on the data on this page',
      })
    ).toHaveAttribute('href', '#main-content');
  });

  it('switches the text with the page', async () => {
    renderApp({path: '/rainmaker/overview', loaded: loaded()});

    await userEvent.click(
      within(menu()).getByRole('link', {name: 'Development'})
    );

    expect(panel()).toHaveTextContent(
      'Two pull requests wait for review, and CI failed on develop yesterday.'
    );
    expect(panel()).not.toHaveTextContent('The sprint is on track');
    // No suggestions on Development: the list is left out, not shown empty.
    expect(
      within(panel()).queryByRole('list', {name: 'Suggestions'})
    ).not.toBeInTheDocument();
  });

  it('switches the text with the project', async () => {
    const forProject = (projectId: string) => {
      const snapshot = structuredClone(sample);
      snapshot.navigator.pages.overview.en.summary = `Summary for ${projectId}.`;
      return toLoadedSnapshot(parseSnapshot(snapshot));
    };
    renderApp({path: '/rainmaker/overview', loaded: forProject});

    await userEvent.click(
      within(menu()).getByRole('link', {name: 'Mission Control'})
    );

    expect(panel()).toHaveTextContent('Summary for mission-control.');
  });

  it('shows the text in the chosen language', async () => {
    renderApp({path: '/rainmaker/overview', loaded: loaded()});

    await userEvent.click(screen.getByRole('button', {name: 'Svenska'}));

    expect(panel()).toHaveTextContent(
      'Sprinten ligger i fas, men en röd risk och en försenad fråga behöver ägarna.'
    );
    expect(panel()).toHaveTextContent(
      'Genererad av AI (gpt-6-luna) kl. 07:00. Kan innehålla fel.'
    );
  });

  it('shows HTML and Markdown in the text as plain text', () => {
    const snapshot = structuredClone(sample);
    snapshot.navigator.pages.overview.en.summary =
      '<img src=x onerror="alert(1)"> see [this](https://example.org) **now**';

    renderApp({
      path: '/rainmaker/overview',
      loaded: toLoadedSnapshot(parseSnapshot(snapshot)),
    });

    expect(panel().querySelector('img')).toBeNull();
    expect(panel().querySelector('strong')).toBeNull();
    expect(
      within(panel()).queryByRole('link', {name: 'this'})
    ).not.toBeInTheDocument();
    expect(panel()).toHaveTextContent(
      '<img src=x onerror="alert(1)"> see [this](https://example.org) **now**'
    );
  });

  it('says "No AI summary yet" with the reason when that page failed', () => {
    renderApp({
      path: '/rainmaker/sources',
      loaded: loaded({
        sources: [...sample.sources, aiSource('ok', 'No AI text for: sources')],
      }),
    });

    expect(panel()).toHaveTextContent('No AI summary yet');
    expect(panel()).toHaveTextContent('No AI text for: sources');
    expect(panel()).not.toHaveTextContent('Generated by AI');
  });

  it('says "No AI summary yet" with the reason when the AI step failed', () => {
    renderApp({
      path: '/rainmaker/overview',
      loaded: loaded({
        navigator: null,
        sources: [...sample.sources, aiSource('error', 'OpenAI timed out')],
      }),
    });

    expect(panel()).toHaveTextContent('No AI summary yet');
    expect(panel()).toHaveTextContent('OpenAI timed out');
  });

  it('hides the AI part when the step is switched off or the snapshot is from before #115', () => {
    const off = renderApp({
      path: '/rainmaker/overview',
      loaded: loaded({
        navigator: null,
        sources: [...sample.sources, aiSource('disabled')],
      }),
    });
    expect(panel()).not.toHaveTextContent('Generated by AI');
    expect(panel()).not.toHaveTextContent('No AI summary yet');
    off.unmount();

    renderApp({path: '/rainmaker/overview', loaded: loaded({navigator: null})});
    expect(panel()).not.toHaveTextContent('No AI summary yet');
  });

  it('hides the AI part on START HERE, which has no AI text', () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response('# Report')));
    renderApp({path: '/rainmaker/start-here', loaded: loaded()});

    expect(panel()).not.toHaveTextContent('Generated by AI');
    expect(panel()).not.toHaveTextContent('No AI summary yet');
    vi.unstubAllGlobals();
  });

  it('shows the stale hint when the text is more than 24 hours old', () => {
    vi.setSystemTime(new Date('2026-11-03T07:00:00Z'));

    renderApp({path: '/rainmaker/overview', loaded: loaded()});

    expect(panel()).toHaveTextContent('The data is more than 24 hours old');
  });

  it('keeps Ask Navigator disabled, saying it comes later', () => {
    renderApp({path: '/rainmaker/overview', loaded: loaded()});

    expect(
      within(panel()).getByRole('textbox', {name: 'Ask your own question'})
    ).toBeDisabled();
    expect(within(panel()).getByRole('button', {name: 'Ask'})).toBeDisabled();
    expect(panel()).toHaveTextContent('Coming later');
  });
});
