import {screen} from '@testing-library/react';
import {afterEach, describe, expect, it, vi} from 'vitest';
import {renderApp} from '../test/renderApp';

describe('Navigator with the demo sample', () => {
  afterEach(() => vi.useRealTimers());

  it('never shows the stale hint for demo data, however old it is', () => {
    vi.useFakeTimers({toFake: ['Date']});
    vi.setSystemTime(new Date('2027-06-01T08:00:00Z'));

    renderApp({path: '/rainmaker/overview'});

    const panel = screen.getByRole('complementary', {name: 'Navigator'});
    expect(panel).toHaveTextContent('Generated by AI (demo)');
    expect(panel).not.toHaveTextContent('The data is more than 24 hours old');
  });
});
